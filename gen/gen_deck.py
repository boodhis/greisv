def frets_deck():
    """Все струны × лады 0–12 в стандартном строе."""
    tuning = ["E2", "A2", "D3", "G3", "B3", "E4"]
    names = ["E", "F", "F#", "G", "G#", "A", "A#", "B", "C", "C#", "D", "D#", "E"]
    strings = [
        ("6-я (E, толстая)", "E2"),
        ("5-я (A)", "A2"),
        ("4-я (D)", "D3"),
        ("3-я (G)", "G3"),
        ("2-я (B)", "B3"),
        ("1-я (e, тонкая)", "E4"),
    ]
    out = []
    for label, base in strings:
        start = names.index(base[0])
        for fret in range(0, 13):
            out.append([
                f"{label} · лад {fret}",
                "",
                names[(start + fret) % 12],
            ])
    return out


