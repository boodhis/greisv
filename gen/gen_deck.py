def load_words():
    words, cmds = [], []
    in_cmds = False
    with open(SRC, encoding="utf-8") as f:
        for ln in f:
            ln = ln.strip()
            if not ln or ln.startswith("#"):
                if "терминал" in ln:
                    in_cmds = True
                continue
            parts = [p.strip() for p in ln.split("|")]
            if len(parts) >= 3:
                w, ph, t = parts[0], parts[1], parts[2]
            elif len(parts) == 2:
                w, ph, t = parts[0], "", parts[1]
            else:
                continue
            if not (w and t):
                continue
            if in_cmds:
                cmds.append([w, ph, t])
            else:
                words.append([w, ph, t])
    return words, cmds


